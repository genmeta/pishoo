const CONTACT_CLASSES = ['human', 'agent', 'robot', 'service', 'admin'] as const

export function contactClassLabel(t: Translator, value: string): string {
  const normalized = value.toLowerCase()
  const kind = CONTACT_CLASSES.find((item) => item === normalized)
  return kind ? t(`contacts.class.${kind}`) : value || t('contacts.unclassified')
}

const CAPABILITY_IDS = ['chat', 'public_profile'] as const

export function capabilityLabel(t: Translator, id: string, field: 'name' | 'summary' = 'name'): string {
  const kind = CAPABILITY_IDS.find((item) => item === id)
  return kind ? t(`capabilities.${kind}.${field}`) : id
}

export type ContactFollowupReason = 'unlisted' | 'remote-not-granted' | 'remote-unknown'

export function contactFollowupLabel(
  t: Translator,
  reason: ContactFollowupReason,
  field: 'label' | 'detail' = 'label',
): string {
  return t(field === 'detail' ? `contacts.followup.${reason}Detail` : `contacts.followup.${reason}`)
}
